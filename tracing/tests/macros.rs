#[cfg_attr(target_arch = "wasm32", wasm_bindgen_test::wasm_bindgen_test)]
#[test]
fn event() {
    event_internal!(Level::DEBUG, foo = ?3, bar.baz = %2, quux = false);
    event_internal!(Level::DEBUG, foo = 3, bar.baz = 2, quux = false);
    event_internal!(Level::DEBUG, foo = 3, bar.baz = 3,);
    event_internal!(Level::DEBUG, "foo");
    event_internal!(Level::DEBUG, "foo: {}", 3);
    event_internal!(Level::INFO, foo = ?3, bar.baz = %2, quux = false, "hello world {:?}", 42);
    event_internal!(
        Level::INFO,
        foo = 3,
        bar.baz = 2,
        quux = false,
        "hello world {:?}",
        42
    );
    event_internal!(Level::INFO, foo = 3, bar.baz = 3, "hello world {:?}", 42,);
    event_internal!(Level::DEBUG, { foo = 3, bar.baz = 80 }, "quux");
    event_internal!(Level::DEBUG, { foo = 2, bar.baz = 79 }, "quux {:?}", true);
    event_internal!(Level::DEBUG, { foo = 2, bar.baz = 79 }, "quux {:?}, {quux}", true, quux = false);
    event_internal!(Level::DEBUG, { foo = ?2, bar.baz = %78 }, "quux");
    event_internal!(target: "foo_events", Level::DEBUG, foo = 3, bar.baz = 2, quux = false);
    event_internal!(target: "foo_events", Level::DEBUG, foo = 3, bar.baz = 3,);
    event_internal!(target: "foo_events", Level::DEBUG, "foo");
    event_internal!(target: "foo_events", Level::DEBUG, "foo: {}", 3);
    event_internal!(target: "foo_events", Level::DEBUG, { foo = 3, bar.baz = 80 }, "quux");
    event_internal!(target: "foo_events", Level::DEBUG, { foo = 2, bar.baz = 79 }, "quux {:?}", true);
    event_internal!(target: "foo_events", Level::DEBUG, { foo = 2, bar.baz = 79 }, "quux {:?}, {quux}", true, quux = false);
    event_internal!(target: "foo_events", Level::DEBUG, { foo = 2, bar.baz = 78, }, "quux");
    let foo = 1;
    event_internal!(Level::DEBUG, ?foo);
    event_internal!(Level::DEBUG, %foo);
    event_internal!(Level::DEBUG, foo);
}

