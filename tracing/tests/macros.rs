// Tests that macros work across various invocation syntax.
//
// These are quite repetitive, and _could_ be generated by a macro. However,
// they're compile-time tests, so I want to get line numbers etc out of
// failures, and producing them with a macro would muddy the waters a bit.

#[cfg_attr(target_arch = "wasm32", wasm_bindgen_test::wasm_bindgen_test)]
#[test]
fn span() {
    span_internal!(target: "foo_events", Level::DEBUG, "foo", bar.baz = ?2, quux = %3, quuux = 4);
    span_internal!(target: "foo_events", Level::DEBUG, "foo", bar.baz = 2, quux = 3);
    span_internal!(target: "foo_events", Level::DEBUG, "foo", bar.baz = 2, quux = 4,);
    span_internal!(target: "foo_events", Level::DEBUG, "foo");
    span_internal!(target: "foo_events", Level::DEBUG, "bar",);
    span_internal!(Level::DEBUG, "foo", bar.baz = 2, quux = 3);
    span_internal!(Level::DEBUG, "foo", bar.baz = 2, quux = 4,);
    span_internal!(Level::DEBUG, "foo", bar.baz = 2, quux = 3);
    span_internal!(Level::DEBUG, "foo", bar.baz = 2, quux = 4,);
    span_internal!(Level::DEBUG, "foo", bar.baz = ?2);
    span_internal!(Level::DEBUG, "foo", bar.baz = %2);
    span_internal!(Level::DEBUG, "foo");
    span_internal!(Level::DEBUG, "bar",);
}

